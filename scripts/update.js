#!/usr/bin/env node
/**
 * update.js — regenerates blog-index.json and photos-data.json
 *
 * Usage:
 *   node scripts/update.js            # update both blog and photos
 *   node scripts/update.js --blog     # blog only
 *   node scripts/update.js --photos   # photos only
 *
 * Cloudinary credentials (required for --photos):
 *   Set as environment variables before running, or create a .env file:
 *     CLOUDINARY_CLOUD_NAME=your_cloud_name
 *     CLOUDINARY_API_KEY=your_api_key
 *     CLOUDINARY_API_SECRET=your_api_secret
 */

const fs      = require('fs');
const path    = require('path');
const matter  = require('gray-matter');
const { marked }       = require('marked');
const sanitizeHtml     = require('sanitize-html');

marked.setOptions({ mangle: false, headerIds: false });

const ROOT = path.join(__dirname, '..');
const SITE_URL = 'https://devrashie.space';
const SITE_NAME = 'Devakh Rashie';
// First line of every page written by writePostPage(); used to find stale pages to remove.
const GENERATED_MARKER = '<!-- generated by scripts/update.js — edit the .md, not this file -->';

// ── Load .env if present ──────────────────────────────────────────────────────
const envPath = path.join(ROOT, '.env');
if (fs.existsSync(envPath)) {
  fs.readFileSync(envPath, 'utf8').split('\n').forEach(line => {
    const m = line.match(/^\s*([^#=\s]+)\s*=\s*(.*)\s*$/);
    if (m) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  });
}

// ── Helpers ───────────────────────────────────────────────────────────────────
function slugify(str) {
  return str.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');
}

function formatDate(d) {
  try {
    const dt = new Date(d);
    if (isNaN(dt)) return '';
    // Front-matter dates parse as UTC midnight; format in UTC so they don't shift a day.
    return dt.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });
  } catch { return ''; }
}

function escapeHtml(s) {
  return String(s || '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

function renderMarkdown(mdContent) {
  const html = marked.parse(mdContent || '');
  return sanitizeHtml(html, {
    allowedTags: sanitizeHtml.defaults.allowedTags.concat(['img', 'h1', 'h2', 'h3']),
    allowedAttributes: {
      ...sanitizeHtml.defaults.allowedAttributes,
      img: ['src', 'alt', 'title', 'width', 'height'],
    },
  });
}

