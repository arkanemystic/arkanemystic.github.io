function writePostPages(blogDir, posts) {
  const slugs = new Set(posts.map(p => p.slug));

  // Remove pages for posts that were deleted or renamed.
  fs.readdirSync(blogDir)
    .filter(f => /\.html$/i.test(f) && !slugs.has(f.replace(/\.html$/i, '')))
    .forEach(f => {
      const fpath = path.join(blogDir, f);
      if (fs.readFileSync(fpath, 'utf8').startsWith(GENERATED_MARKER)) {
        fs.unlinkSync(fpath);
        console.log(`  removed stale blog/${f}`);
      }
    });

  posts.forEach(post => {
    fs.writeFileSync(path.join(blogDir, `${post.slug}.html`), postPageHtml(post));
  });
}

// ── Blog ──────────────────────────────────────────────────────────────────────
async function updateBlog() {
  const blogDir   = path.join(ROOT, 'blog');
  const indexPath = path.join(ROOT, 'blog-index.json');

  if (!fs.existsSync(blogDir)) {
    console.log('No blog/ directory found — skipping blog update.');
    return;
  }

  const files = fs.readdirSync(blogDir).filter(f => /\.md$/i.test(f));
  if (!files.length) {
    console.log('No .md files in blog/ — writing empty index.');
    fs.writeFileSync(indexPath, JSON.stringify({ posts: [] }, null, 2));
    writePostPages(blogDir, []);
    return;
  }

  const posts = files.map(fname => {
    const fpath   = path.join(blogDir, fname);
    const raw     = fs.readFileSync(fpath, 'utf8');
    const fm      = matter(raw);
    const title   = fm.data.title || fname.replace(/\.md$/i, '').replace(/-/g, ' ');
    const date    = fm.data.date
      ? new Date(fm.data.date).toISOString()
      : fs.statSync(fpath).mtime.toISOString();
    const slug    = slugify(String(fm.data.slug || title));
    const excerpt = fm.data.excerpt
      || fm.content.split('\n').find(l => l.trim() && !l.startsWith('#'))?.slice(0, 200)
      || '';
    const html    = renderMarkdown(fm.content);

    return { title, slug, url: `/blog/${slug}`, date, dateFormatted: formatDate(date), excerpt, html, source: fname };
  });

  const bySlug = new Map();
  posts.forEach(p => {
    if (bySlug.has(p.slug)) {
      throw new Error(`blog/${p.source} and blog/${bySlug.get(p.slug)} both use the slug "${p.slug}" — set a different \`slug:\` in one of them.`);
    }
    bySlug.set(p.slug, p.source);
  });

  // Newest first
  posts.sort((a, b) => new Date(b.date) - new Date(a.date));

  writePostPages(blogDir, posts);

  // The homepage only needs enough to list posts; the body lives on each post's page.
  const index = posts.map(({ title, slug, url, date, dateFormatted, excerpt }) =>
    ({ title, slug, url, date, dateFormatted, excerpt }));
  fs.writeFileSync(indexPath, JSON.stringify({ posts: index }, null, 2));
  console.log(`✓ blog-index.json + blog/*.html — ${posts.length} post(s)`);
  posts.forEach(p => console.log(`  ${SITE_URL}${p.url}`));
}

// ── Photos ────────────────────────────────────────────────────────────────────
async function updatePhotos() {
  const cloudName  = process.env.CLOUDINARY_CLOUD_NAME;
  const apiKey     = process.env.CLOUDINARY_API_KEY;
  const apiSecret  = process.env.CLOUDINARY_API_SECRET;
  const folder     = process.env.CLOUDINARY_FOLDER === undefined ? 'photos' : process.env.CLOUDINARY_FOLDER;

  if (!cloudName || !apiKey || !apiSecret) {
    console.error(
      'Missing Cloudinary credentials.\n' +
      'Set CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY, CLOUDINARY_API_SECRET\n' +
      'in your environment or in a .env file at the project root.'
    );
    process.exit(1);
  }

  const cloudinary = require('cloudinary').v2;
  cloudinary.config({ cloud_name: cloudName, api_key: apiKey, api_secret: apiSecret });

  console.log(`Fetching photos from Cloudinary folder "${folder}"…`);
  let resources = [];
  let nextCursor;

  do {
    const opts = { type: 'upload', max_results: 500 };
    if (folder) opts.prefix = folder;
    if (nextCursor) opts.next_cursor = nextCursor;
    const res = await cloudinary.api.resources(opts);
    resources = resources.concat(res.resources || []);
    nextCursor = res.next_cursor;
  } while (nextCursor);

  const out = resources.map(r => ({
    public_id:  r.public_id,
    secure_url: r.format === 'heic'
      ? r.secure_url.replace('/upload/', '/upload/f_jpg,q_auto/')
      : r.secure_url,
    photo_date: r.created_at,
  }));

  // Newest first
  out.sort((a, b) => new Date(b.photo_date) - new Date(a.photo_date));

  const outPath = path.join(ROOT, 'photos-data.json');
  fs.writeFileSync(outPath, JSON.stringify({ resources: out }, null, 2));
  console.log(`✓ photos-data.json — ${out.length} photo(s)`);
}

// ── Main ──────────────────────────────────────────────────────────────────────
(async () => {
  const args    = process.argv.slice(2);
  const blogOnly   = args.includes('--blog');
  const photosOnly = args.includes('--photos');
  const both = !blogOnly && !photosOnly;

  try {
    if (both || blogOnly)   await updateBlog();
    if (both || photosOnly) await updatePhotos();
  } catch (err) {
    console.error(err);
    process.exit(1);
  }
})();
